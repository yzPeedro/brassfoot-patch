const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root,'index.html'),'utf8');
const js = fs.readFileSync(path.join(root,'app.js'),'utf8');
const css = fs.readFileSync(path.join(root,'styles.css'),'utf8');
const release = JSON.parse(fs.readFileSync(path.join(root,'data/release.json'),'utf8'));
const sections = ['inicio','recursos','como-funciona','versao','faq'];
for(const sec of sections)assert.match(html,new RegExp(`id="${sec}"`));
assert.match(release.downloadUrl,/releases\/download\/v2026\.0\.2\/Brassfoot-Patch-2026-Setup\.exe$/);
assert.equal(release.status,'awaiting_release');
assert.equal(release.compatibilityVerifiedInGame,true);
assert.match(html,/disabled aria-describedby="release-status-text"/);
assert.doesNotMatch(html,/href="https:\/\/github\.com\/"/);
assert.match(js,/compatibilityVerifiedInGame\s*!==\s*true/);
assert.match(js,/sha256/);
assert.match(js,/api\.github\.com\/repos\/yzPeedro/);
assert.match(js,/item\.digest === 'sha256:'/);
assert.equal(release.fileSizeBytes,2799616);
assert.match(css,/prefers-reduced-motion/);
assert.doesNotMatch(html,/class="ball"/);
assert.doesNotMatch(css,/\.ball\{|@keyframes float-ball/);
assert.match(html,/class="field-scan"/);
assert.match(css,/@keyframes fieldscan/);
assert.match(html,/a atualização dos elencos foi testada no Brasfoot pelo mantenedor/i);

assert.ok(!/x-apisports-key|API_FOOTBALL_KEY|\bVITE_/.test(html+js+css));
console.log(`Site static checks: ${sections.length} sections, release safely disabled, no exposed API key.`);
